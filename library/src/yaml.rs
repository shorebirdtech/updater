/// Controls when patch signature verification occurs.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum PatchVerificationMode {
    /// Verify patch signature at install time and again at every boot.
    /// Re-hashing the patch on each boot also catches a patch file changed
    /// on disk after installation, at the cost of boot time.
    Strict,
    /// Verify patch signature at install time only (default).
    /// A forged or tampered offer is refused before it is downloaded, so
    /// this covers a network attacker; it skips the per-boot re-hash.
    /// Default only because install-time verification (#396) exists: never
    /// backport this default to an updater without it.
    #[default]
    InstallOnly,
}

/// Struct for parsing shorebird.yaml.
#[derive(Debug)]
pub struct YamlConfig {
    /// App ID.  Required.  Generated by Shorebird and included
    /// in your app to identify which app/channel/version triple to update.
    pub app_id: String,
    /// Update channel name.  Defaults to "stable" if not set.
    pub channel: Option<String>,
    /// Update URL.  Defaults to the default update URL if not set.
    pub base_url: Option<String>,
    /// Update behavior. Defaults to true if not set.
    pub auto_update: Option<bool>,
    /// Base64-encoded public key for verifying patch hash signatures.
    pub patch_public_key: Option<String>,
    /// When to verify patch signatures. Defaults to "install_only" (verify at install time).
    pub patch_verification: Option<PatchVerificationMode>,
    /// An add-to-app module's own release version, which the Flutter tool
    /// writes into the module's compiled shorebird.yaml. When present the
    /// updater sends it as `release_version` in place of the host app's
    /// version, so one module release is patched in every host app.
    pub release_version: Option<String>,
}

/// Longest `release_version` accepted from shorebird.yaml.
const MAX_RELEASE_VERSION_LEN: usize = 128;

/// Strips one pair of matching YAML quotes. The Flutter tool writes the
/// value through a YAML emitter, which quotes values that would otherwise
/// read back as numbers (`1.10`).
fn unquote(value: &str) -> &str {
    for quote in ['\'', '"'] {
        if let Some(inner) = value
            .strip_prefix(quote)
            .and_then(|rest| rest.strip_suffix(quote))
        {
            return inner;
        }
    }
    value
}

/// Parses a baked `release_version`: one to 128 of `[A-Za-z0-9._+-]`.
/// Anything else is refused, which fails init and leaves the app on its
/// installed version rather than asking the server about a release the
/// module was never built as.
fn parse_release_version(value: &str) -> Result<String, String> {
    let version = unquote(value);
    let valid_chars = version
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '+' | '-'));
    if version.is_empty() || version.len() > MAX_RELEASE_VERSION_LEN || !valid_chars {
        return Err(format!("invalid value for release_version: '{value}'"));
    }
    Ok(version.to_string())
}

impl YamlConfig {
    /// Read in shorebird.yaml from a string.
    ///
    /// This is a minimal parser for simple key-value YAML (no nesting,
    /// no flow syntax, no anchors). This is sufficient for shorebird.yaml
    /// which we fully control.
    pub fn from_yaml(yaml: &str) -> Result<Self, String> {
        let mut app_id: Option<String> = None;
        let mut channel: Option<String> = None;
        let mut base_url: Option<String> = None;
        let mut auto_update: Option<bool> = None;
        let mut patch_public_key: Option<String> = None;
        let mut patch_verification: Option<PatchVerificationMode> = None;
        let mut release_version: Option<String> = None;

        for line in yaml.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }

            let Some((key, value)) = line.split_once(':') else {
                continue;
            };
            let key = key.trim();
            let value = value.trim();

            match key {
                "app_id" => app_id = Some(value.to_string()),
                "channel" => channel = Some(value.to_string()),
                "base_url" => base_url = Some(value.to_string()),
                "auto_update" => {
                    auto_update =
                        Some(value.parse::<bool>().map_err(|e| {
                            format!("invalid value for auto_update: '{value}': {e}")
                        })?);
                }
                "patch_public_key" => patch_public_key = Some(value.to_string()),
                "patch_verification" => {
                    patch_verification = Some(match value {
                        "strict" => PatchVerificationMode::Strict,
                        "install_only" => PatchVerificationMode::InstallOnly,
                        _ => {
                            return Err(format!("invalid value for patch_verification: '{value}'"))
                        }
                    });
                }
                "release_version" => release_version = Some(parse_release_version(value)?),
                _ => {} // Ignore unknown keys for forward compatibility.
            }
        }

        let app_id = app_id.ok_or("missing required field: app_id")?;

        Ok(YamlConfig {
            app_id,
            channel,
            base_url,
            auto_update,
            patch_public_key,
            patch_verification,
            release_version,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_patch_verification_strict() {
        let yaml = r#"
app_id: test_app
patch_verification: strict
"#;
        let config = YamlConfig::from_yaml(yaml).unwrap();
        assert_eq!(
            config.patch_verification,
            Some(PatchVerificationMode::Strict)
        );
    }

    #[test]
    fn parses_patch_verification_install_only() {
        let yaml = r#"
app_id: test_app
patch_verification: install_only
"#;
        let config = YamlConfig::from_yaml(yaml).unwrap();
        assert_eq!(
            config.patch_verification,
            Some(PatchVerificationMode::InstallOnly)
        );
    }

    #[test]
    fn defaults_to_none_when_not_specified() {
        let yaml = r#"
app_id: test_app
"#;
        let config = YamlConfig::from_yaml(yaml).unwrap();
        assert_eq!(config.patch_verification, None);
        // When unwrapped with default, should be InstallOnly
        assert_eq!(
            config.patch_verification.unwrap_or_default(),
            PatchVerificationMode::InstallOnly
        );
    }

    #[test]
    fn default_verification_mode_is_install_only() {
        assert_eq!(
            PatchVerificationMode::default(),
            PatchVerificationMode::InstallOnly
        );
    }

    #[test]
    fn missing_app_id_is_error() {
        let yaml = "channel: stable\n";
        let result = YamlConfig::from_yaml(yaml);
        assert!(result.is_err());
        assert!(result.unwrap_err().contains("app_id"));
    }

    #[test]
    fn parses_all_fields() {
        let yaml = r#"
app_id: my_app
channel: beta
base_url: https://example.com
auto_update: false
patch_public_key: abc123
patch_verification: install_only
"#;
        let config = YamlConfig::from_yaml(yaml).unwrap();
        assert_eq!(config.app_id, "my_app");
        assert_eq!(config.channel.as_deref(), Some("beta"));
        assert_eq!(config.base_url.as_deref(), Some("https://example.com"));
        assert_eq!(config.auto_update, Some(false));
        assert_eq!(config.patch_public_key.as_deref(), Some("abc123"));
        assert_eq!(
            config.patch_verification,
            Some(PatchVerificationMode::InstallOnly)
        );
    }

    #[test]
    fn ignores_comments_and_blank_lines() {
        let yaml = r#"
# This is a comment
app_id: test_app

# Another comment
channel: stable
"#;
        let config = YamlConfig::from_yaml(yaml).unwrap();
        assert_eq!(config.app_id, "test_app");
        assert_eq!(config.channel.as_deref(), Some("stable"));
    }

    #[test]
    fn ignores_unknown_keys() {
        let yaml = r#"
app_id: test_app
unknown_key: some_value
"#;
        let config = YamlConfig::from_yaml(yaml).unwrap();
        assert_eq!(config.app_id, "test_app");
    }

    #[test]
    fn invalid_auto_update_is_error() {
        let yaml = r#"
app_id: test_app
auto_update: maybe
"#;
        let result = YamlConfig::from_yaml(yaml);
        assert!(result.is_err());
        assert!(result.unwrap_err().contains("auto_update"));
    }

    #[test]
    fn fields_in_any_order() {
        let yaml = r#"
patch_verification: strict
base_url: https://example.com
app_id: my_app
auto_update: true
channel: beta
patch_public_key: abc123
"#;
        let config = YamlConfig::from_yaml(yaml).unwrap();
        assert_eq!(config.app_id, "my_app");
        assert_eq!(config.channel.as_deref(), Some("beta"));
        assert_eq!(config.base_url.as_deref(), Some("https://example.com"));
        assert_eq!(config.auto_update, Some(true));
        assert_eq!(config.patch_public_key.as_deref(), Some("abc123"));
        assert_eq!(
            config.patch_verification,
            Some(PatchVerificationMode::Strict)
        );
    }

    #[test]
    fn invalid_patch_verification_is_error() {
        let yaml = r#"
app_id: test_app
patch_verification: unknown_mode
"#;
        let result = YamlConfig::from_yaml(yaml);
        assert!(result.is_err());
        assert!(result.unwrap_err().contains("patch_verification"));
    }

    #[test]
    fn release_version_absent_is_none() {
        let config = YamlConfig::from_yaml("app_id: a").unwrap();
        assert_eq!(config.release_version, None);
    }

    #[test]
    fn release_version_strips_quotes() {
        for (yaml, expected) in [
            ("release_version: 1.2.3+4", "1.2.3+4"),
            ("release_version: '1.10'", "1.10"),
            ("release_version: \"1.10\"", "1.10"),
            ("release_version: 'v2_rc-1'", "v2_rc-1"),
        ] {
            let config = YamlConfig::from_yaml(&format!("app_id: a\n{yaml}")).unwrap();
            assert_eq!(config.release_version.as_deref(), Some(expected), "{yaml}");
        }
    }

    #[test]
    fn release_version_at_max_length_is_accepted() {
        let version = "1".repeat(128);
        let config =
            YamlConfig::from_yaml(&format!("app_id: a\nrelease_version: {version}")).unwrap();
        assert_eq!(config.release_version, Some(version));
    }

    #[test]
    fn invalid_release_version_is_error() {
        for value in [
            "",
            "''",
            "'1.0",
            "'1.0\"",
            "1.0 beta",
            "1.0/2",
            "1.0é",
            "'it''s'",
            &"1".repeat(129),
        ] {
            let err =
                YamlConfig::from_yaml(&format!("app_id: a\nrelease_version: {value}")).unwrap_err();
            assert!(err.contains("release_version"), "{value}: {err}");
        }
    }
}
